def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True, help="包含 specs 和 agent-runtime 的项目根目录")
    parser.add_argument("--output", type=Path, help="将场景清单写入工作区文件；不填写则打印")
    args = parser.parse_args()
    nodes = {node["id"]: node for node in json.loads((args.root / "specs/nodes.json").read_text(encoding="utf-8"))["nodes"]}
    profiles = {node["agentRole"] for node in nodes.values()}
    available = {json.loads((p / "profile.json").read_text(encoding="utf-8"))["id"]
                 for p in (args.root / "agent-runtime/profiles").iterdir() if p.is_dir()}
    if not profiles <= available:
        raise ValueError("节点专家缺少角色包")
    roles = [case[0] for case in CASES]
    if len(roles) != len(set(roles)) or set(roles) != profiles:
        raise ValueError("场景角色必须与专家目录一一对应")
    for group in (SPECIALIST_CASES, ADVERSARIAL_CASES):
        if len(group) != len(profiles) or {case[0] for case in group} != profiles:
            raise ValueError("各类场景必须覆盖所有专家且每个角色一条")
    records = []
    for index, (role, node_id, task_input, expected, forbidden) in enumerate(CASES + SPECIALIST_CASES + ADVERSARIAL_CASES):
        node = nodes[node_id]
        if node["agentRole"] != role or not node["output"]["requiredFields"]:
            raise ValueError(f"节点与角色或字段不匹配: {role} {node_id}")
        if not task_input or len(expected) < 2 or len(forbidden) < 2:
            raise ValueError(f"场景缺少可观察的通过/失败标准: {role}")
        suffix = "" if index < len(CASES) else "-specialist" if index < len(CASES) + len(SPECIALIST_CASES) else "-adversarial"
        records.append({"id": f"offline-{role.lower()}{suffix}", "role": role, "nodeId": node_id,
                        "input": task_input, "requiredFields": node["output"]["requiredFields"],
                        "humanReviewExpected": expected, "humanReviewForbidden": forbidden})
    result = {"version": "1.2", "kind": "human-review-scenarios",
              "notice": "仅检查场景与节点配置一致；未运行模型、未判定领域能力。测试资料均为虚构。",
              "cases": records}
    text = json.dumps(result, ensure_ascii=False, indent=2) + "\n"
    if args.output:
        args.output.write_text(text, encoding="utf-8")
        print(f"场景配置检查通过：{len(records)} 条，已写入 {args.output}")
    else:
        print(text)


if __name__ == "__main__":
    main()
